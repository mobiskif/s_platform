#!/usr/bin/env python3
"""Генерирует векторное лицо кардинала Ришельё (слои путей) -> assets/richelieu.txt

Формат строки: группа|заливка|прозрачность|обводка|толщина|путь   ('-' = нет)
Группы: s (статика), brows (брови), lids (веки), mouth (полость рта), jaw (нижняя губа и бородка)
Путь: только абсолютные M L C Q Z, числа через пробел.
Система координат: 200 x 240, центр лица x = 100.
"""
import os, sys

K = 0.5523  # константа Безье для окружности

def ell(cx, cy, rx, ry):
    return ("M {a} {cy} C {a} {y1} {x1} {t} {cx} {t} C {x2} {t} {b} {y1} {b} {cy} "
            "C {b} {y2} {x2} {bt} {cx} {bt} C {x1} {bt} {a} {y2} {a} {cy} Z").format(
        cx=cx, cy=cy, a=cx - rx, b=cx + rx, t=cy - ry, bt=cy + ry,
        x1=cx - rx * K, x2=cx + rx * K, y1=cy - ry * K, y2=cy + ry * K)

L = []  # (group, fill, opacity, stroke, sw, path)
def add(g, d, fill='-', op=1, stroke='-', sw=0):
    L.append((g, fill, op, stroke, sw, d))

SKIN, SKIN_D = '#e2c3a4', '#a87b5a'
RED, RED_D = '#b5121b', '#6e0710'
HAIR = '#3b2f2a'

# --- фон: тёмный бархат + свечение за головой
add('s', 'M 0 0 L 200 0 L 200 240 L 0 240 Z', '#240910')
add('s', ell(100, 105, 92, 108), '#5a1822', 0.85)
add('s', ell(100, 105, 70, 86), '#7a2330', 0.45)

# --- плечи: красная мантелетта
add('s', 'M 0 240 L 0 214 C 22 192 55 180 76 172 L 124 172 C 145 180 178 192 200 214 L 200 240 Z', RED)
add('s', 'M 0 240 L 0 226 C 40 212 80 206 100 206 C 120 206 160 212 200 226 L 200 240 Z', RED_D, 0.35)
# --- белый рочет (воротник)
add('s', 'M 66 168 L 134 168 L 146 192 C 124 204 76 204 54 192 Z', '#f3eee2')
add('s', 'M 66 168 L 134 168 L 140 180 C 120 190 80 190 60 180 Z', '#c9c0ad', 0.45)
# --- красный вырез мантелетты поверх воротника (V)
add('s', 'M 54 192 C 76 204 124 204 146 192 L 150 200 C 124 214 76 214 50 200 Z', RED)
# --- шея
add('s', 'M 84 140 L 82 172 C 90 184 110 184 118 172 L 116 140 Z', SKIN)
add('s', 'M 83 150 L 117 150 L 118 172 C 110 184 90 184 82 172 Z', '#6b4630', 0.3)
add('s', ell(100, 156, 22, 8), '#4a2c1a', 0.28)
# --- пуговицы мантелетты
for i in range(5):
    add('s', ell(100, 214 + i * 7.5, 1.6, 1.6), RED_D)
# --- цепь и золотой наперсный крест
add('s', 'M 66 184 C 76 200 92 208 100 216', '-', 1, '#d9b13f', 1.4)
add('s', 'M 134 184 C 124 200 108 208 100 216', '-', 1, '#d9b13f', 1.4)
add('s', 'M 98 214 L 102 214 L 102 220 L 107 220 L 107 224 L 102 224 L 102 236 L 98 236 L 98 224 L 93 224 L 93 220 L 98 220 Z', '#e2bb45', 1, '#8d6a12', 0.6)

# --- волосы сзади и уши
add('s', 'M 55 74 C 44 96 46 122 56 138 L 64 124 L 64 80 Z', HAIR)
add('s', 'M 145 74 C 156 96 154 122 144 138 L 136 124 L 136 80 Z', HAIR)
add('s', ell(59, 104, 5, 10), SKIN)
add('s', ell(141, 104, 5, 10), SKIN)
# --- голова
HEAD = ('M 60 66 C 58 96 62 124 78 144 C 88 155 112 155 122 144 '
        'C 138 124 142 96 140 66 Z')
add('s', HEAD, SKIN)
# тени: впалые щёки, виски, под скулами
add('s', ell(75, 124, 8, 14), SKIN_D, 0.14)
add('s', ell(125, 124, 8, 14), SKIN_D, 0.14)
add('s', ell(69, 90, 6, 14), SKIN_D, 0.18)
add('s', ell(131, 90, 6, 14), SKIN_D, 0.18)
add('s', ell(100, 76, 26, 7), '#fff4e0', 0.18)       # блик на лбу
# морщины на лбу
add('s', 'M 80 76 Q 100 73 120 76', '-', 1, '#8a6246', 0.9)
add('s', 'M 84 82 Q 100 79.5 116 82', '-', 0.7, '#8a6246', 0.8)
# складки от носа к губам
add('s', 'M 88 112 C 84 120 84 128 87 134', '-', 0.8, '#8a6246', 1.0)
add('s', 'M 112 112 C 116 120 116 128 113 134', '-', 0.8, '#8a6246', 1.0)

# --- брови
add('brows', 'M 72 92 Q 84 83 96 90', '-', 1, HAIR, 2.6)
add('brows', 'M 104 90 Q 116 83 128 92', '-', 1, HAIR, 2.6)

# --- глаза
for ex in (84, 116):
    add('s', ell(ex, 99, 8, 4), '#f6f0e4')
    add('s', ell(ex, 99, 3.4, 3.4), '#4a3220')
    add('s', ell(ex, 99, 1.6, 1.6), '#0d0907')
    add('s', ell(ex - 1.1, 97.8, 0.9, 0.9), '#ffffff', 0.9)
    add('lids', ell(ex, 98.6, 8.6, 4.8), SKIN)            # век (моргание)
    add('s', 'M {a} 99.4 Q {c} 93.2 {b} 99.4'.format(a=ex - 8.6, b=ex + 8.6, c=ex), '-', 1, '#4a3023', 1.5)
    add('s', 'M {a} 103 Q {c} 106 {b} 103'.format(a=ex - 6.5, b=ex + 6.5, c=ex), '-', 0.45, '#8a6246', 1.0)
# --- нос: длинный, с горбинкой
add('s', 'M 102 98 C 105 108 107 115 106.5 121 L 101 122.5 Z', SKIN_D, 0.28)
add('s', 'M 98.5 96 C 97 108 94.5 114 93 120', '-', 1, '#a47a5a', 1.3)
add('s', 'M 93 121 Q 100 126 107 121', '-', 1, '#7a5239', 1.6)
add('s', ell(96.5, 122, 1.6, 1.0), '#5a3a28', 0.8)
add('s', ell(103.5, 122, 1.6, 1.0), '#5a3a28', 0.8)

# --- рот
add('s', 'M 89 136 Q 100 138.6 111 136', '-', 1, '#7a3f3a', 1.6)          # линия рта (закрыт)
# полость рта: при openness=1 — максимум (масштабируется по Y от линии рта y=136)
add('mouth', 'M 88.5 136 Q 100 134.2 111.5 136 Q 109 153 100 153 Q 91 153 88.5 136 Z', '#3d0a10')
add('mouth', 'M 94 136 Q 100 135 106 136 L 105.5 141.5 Q 100 142.5 94.5 141.5 Z', '#f6efe0')   # верхние зубы
add('mouth', ell(100, 148.5, 6.5, 3.6), '#b54e4c')                                              # язык
add('s', 'M 90 136 Q 100 133.6 110 136', '-', 1, '#a86a5e', 1.3)           # верхняя губа

# --- усы: тонкие, с загнутыми кончиками
MUST = ('M 100 128 C 95 125 87 126 79 130 C 76 131 73 129 71 125 '
        'C 73 134 84 135 100 132.5 C 116 135 127 134 129 125 '
        'C 127 129 124 131 121 130 C 113 126 105 125 100 128 Z')
add('s', MUST, HAIR)
add('s', 'M 88 128.6 C 92 127.4 96 127.4 99 129', '-', 0.35, '#b9b1a6', 0.8)
add('s', 'M 112 128.6 C 108 127.4 104 127.4 101 129', '-', 0.35, '#b9b1a6', 0.8)

# --- челюсть (двигается): нижняя губа и «королевская» бородка клинышком
add('jaw', 'M 91 137.2 Q 100 144.2 109 137.2 Q 100 140.6 91 137.2 Z', '#b9756a')
add('jaw', 'M 95.5 143.8 C 94 148 95 152 97 155 C 98 158 99 161 100 167 '
           'C 101 161 102 158 103 155 C 105 152 106 148 104.5 143.8 '
           'C 102 146 98 146 95.5 143.8 Z', HAIR)
add('jaw', 'M 98.5 150 C 99.5 156 100 160 100 164', '-', 0.35, '#b9b1a6', 0.7)

# --- шапочка (бирета) кардинала
BIR = ('M 53 70 C 49 52 57 36 74 32 C 80 24 92 21 100 27 C 108 21 120 24 126 32 '
       'C 143 36 151 52 147 70 C 130 63 70 63 53 70 Z')
add('s', ell(100, 76, 30, 7), '#1a0c08', 0.10)                # тень под шапочкой
add('s', BIR, '#c1121f')
add('s', 'M 53 70 C 70 63 130 63 147 70 L 146 74 C 128 67 72 67 54 74 Z', '#8f0d18')
add('s', 'M 100 27 C 99 40 100 52 100 64', '-', 1, '#7a0a14', 1.5)
add('s', 'M 74 32 C 78 44 80 56 82 65', '-', 1, '#7a0a14', 1.5)
add('s', 'M 126 32 C 122 44 120 56 118 65', '-', 1, '#7a0a14', 1.5)
add('s', 'M 62 46 C 66 40 72 36 78 34', '-', 0.35, '#ff7b7b', 2.0)    # блик
# волосы по бокам лба из-под шапочки
add('s', 'M 55 72 C 52 80 54 90 58 98 L 62 96 C 60 88 60 80 62 73 Z', HAIR)
add('s', 'M 145 72 C 148 80 146 90 142 98 L 138 96 C 140 88 140 80 138 73 Z', HAIR)


def write(path):
    with open(path, 'w', encoding='utf-8') as f:
        for g, fill, op, stroke, sw, d in L:
            f.write('|'.join([g, fill, '%g' % op, stroke, '%g' % sw, d]) + '\n')

if __name__ == '__main__':
    write(sys.argv[1] if len(sys.argv) > 1 else 'richelieu.txt')
